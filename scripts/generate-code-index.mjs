/**
 * File: generate-code-index.mjs
 * Purpose: Generate exact C, C++, JavaScript, shell, and CMake declaration locations.
 * Symbols and line locations: this script generates docs/code-index.md, including itself.
 * Important variables: patterns and supportedExtensions define the documented source surface.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(root, "docs", "code-index.md");
const supportedExtensions = new Set([".c", ".cpp", ".h", ".hpp", ".mjs", ".sh"]);
const excludedDirectories = new Set([".git", ".cache", "build", "coverage", "dist", "out"]);
const typePattern = /^\s*(?:class|struct|enum(?:\s+class)?)\s+([A-Za-z_][\w]*)/;
const functionPattern = /^\s*(?:\[\[[^\]]+\]\]\s*)?(?:(?:constexpr|explicit|inline|static|virtual)\s+)*(?:[\w:<>,*&]+\s+)+((?:[A-Za-z_][\w]*::)*(?:~?[A-Za-z_][\w]*|operator(?:<=>|==|\[\]|\(\)|[-+*/=<>]+)))\s*\(/;
const qualifiedConstructorPattern = /^\s*((?:[A-Za-z_][\w]*::)+~?[A-Za-z_][\w]*)\s*\(/;
const constantPattern = /^\s*(?:inline\s+)?constexpr\s+(?:[\w:<>,*&]+\s+)+([A-Za-z_][\w]*)\b/;
const inferredVariablePattern = /^\s*(?:const\s+)?auto(?:\s*[*&])?\s+([A-Za-z_][\w]*)\s*(?:=|\{)/;
const fieldPattern = /^\s*(?:std::[\w:<>, ]+|[A-Za-z_][\w:<>]*)\s+([A-Za-z_][\w]*_?)\s*\{[^}]*\}\s*;/;

/** Recursively list authored source files while excluding build and generated trees. */
function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return excludedDirectories.has(entry.name) ? [] : walk(path);
    if (supportedExtensions.has(extname(path)) || basename(path) === "CMakeLists.txt") return [path];
    return [];
  });
}

/** Extract first matching named declaration from every physical line. */
function declarations(path) {
  const extension = extname(path);
  const lines = readFileSync(path, "utf8").split(/\r?\n/);
  const knownTypes = new Set(lines.flatMap((line) => line.match(typePattern)?.[1] ?? []));
  return lines.flatMap((line, index) => {
    if (extension === ".mjs") {
      const match = line.match(/\b(?:function|class)\s+([A-Za-z_$][\w$]*)/) ??
                    line.match(/\b(?:const|let)\s+([A-Za-z_$][\w$]*)\b/);
      return match ? [{ line: index + 1, name: match[1] }] : [];
    }
    if (extension === ".sh") {
      const match = line.match(/^([A-Za-z_][\w]*)\s*\(\)/) ??
                    line.match(/^([A-Z_][A-Z0-9_]*)=/);
      return match ? [{ line: index + 1, name: match[1] }] : [];
    }
    const type = line.match(typePattern);
    if (type) return [{ line: index + 1, name: type[1] }];
    if (/^\s*(?:if|for|while|switch|return|throw|catch)\b/.test(line)) return [];
    const functionMatch = line.match(functionPattern);
    if (functionMatch) return [{ line: index + 1, name: functionMatch[1] }];
    const qualifiedConstructor = line.match(qualifiedConstructorPattern);
    if (qualifiedConstructor) {
      const parts = qualifiedConstructor[1].split("::");
      if (parts.at(-1).replace(/^~/, "") === parts.at(-2)) {
        return [{ line: index + 1, name: qualifiedConstructor[1] }];
      }
    }
    const simpleConstructor = line.match(/^\s*(?:explicit\s+)?([A-Za-z_][\w]*)\s*\(/);
    if (simpleConstructor && knownTypes.has(simpleConstructor[1])) {
      return [{ line: index + 1, name: simpleConstructor[1] }];
    }
    const splitDeclaration = line.match(/^([A-Za-z_][\w]*)\s*\([^;]*\)\s*;/);
    if (splitDeclaration) return [{ line: index + 1, name: splitDeclaration[1] }];
    const variable = line.match(constantPattern) ?? line.match(inferredVariablePattern) ??
                     line.match(fieldPattern);
    return variable ? [{ line: index + 1, name: variable[1] }] : [];
  });
}

/** Render stable Markdown for code review and freshness validation. */
function render() {
  const lines = [
    "# Code index",
    "",
    "Generated by `scripts/generate-code-index.mjs`. Source headers point here for exact",
    "declaration locations. Regenerate after authored source changes.",
    "",
  ];
  for (const path of walk(root).sort()) {
    const items = declarations(path);
    if (items.length === 0) continue;
    const repositoryPath = relative(root, path).replaceAll("\\", "/");
    lines.push(`## \`${repositoryPath}\``, "");
    for (const item of items) lines.push(`- Line ${item.line}: \`${item.name}\``);
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/** Write the index or fail when the committed version is stale. */
function main() {
  const content = render();
  if (process.argv.includes("--check")) {
    if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== content) {
      console.error("docs/code-index.md is stale; run node scripts/generate-code-index.mjs");
      process.exitCode = 1;
      return;
    }
    console.log("Code index is current.");
    return;
  }
  writeFileSync(outputPath, content, "utf8");
  console.log("Generated docs/code-index.md.");
}

main();
